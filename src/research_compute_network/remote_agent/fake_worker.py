"""Fixed-function worker used to validate the sealed SSH execution path.

The worker accepts only a small structured job document generated by the
control plane.  It cannot execute a command, import user code, or choose an
arbitrary output path.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import time
from datetime import datetime, timezone
from pathlib import Path


PROFILE_ID = "rcn-safe-fake-v1"
RESULT_NAME = "safe-fake-result.json"
ALLOWED_KEYS = {
    "schema_version",
    "profile_id",
    "acceptance_nonce",
    "duration_seconds",
    "out_manifest",
}


def iso_now() -> str:
    return datetime.now(timezone.utc).isoformat()


def load_job(path: Path) -> dict:
    value = json.loads(path.read_text(encoding="utf-8-sig"))
    if not isinstance(value, dict) or set(value) != ALLOWED_KEYS:
        raise ValueError("safe fake job contains unsupported fields")
    if value.get("schema_version") != 1 or value.get("profile_id") != PROFILE_ID:
        raise ValueError("safe fake job profile is invalid")
    nonce = value.get("acceptance_nonce")
    if not isinstance(nonce, str) or not nonce or len(nonce) > 128:
        raise ValueError("safe fake acceptance nonce is invalid")
    if any(character not in "abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_.-" for character in nonce):
        raise ValueError("safe fake acceptance nonce is unsafe")
    duration = value.get("duration_seconds")
    if not isinstance(duration, (int, float)) or isinstance(duration, bool) or not 0.1 <= float(duration) <= 30:
        raise ValueError("safe fake duration must be between 0.1 and 30 seconds")
    return value


def validate_output_path(job: dict, *, working_directory: Path) -> Path:
    expected = (working_directory / "output" / RESULT_NAME).resolve()
    candidate = Path(job["out_manifest"]).resolve()
    if candidate != expected:
        raise ValueError("safe fake output path is not the fixed sandbox result path")
    return candidate


def run_job(job_path: Path) -> Path:
    job = load_job(job_path)
    output = validate_output_path(job, working_directory=Path.cwd())
    output.parent.mkdir(parents=True, exist_ok=True)
    started_at = iso_now()
    deadline = time.monotonic() + float(job["duration_seconds"])
    digest = hashlib.sha256(job["acceptance_nonce"].encode("utf-8"))
    iterations = 0
    while time.monotonic() < deadline:
        digest.update(str(iterations).encode("ascii"))
        iterations += 1
        time.sleep(0.05)
    payload = {
        "schema_version": 1,
        "profile_id": PROFILE_ID,
        "acceptance_nonce": job["acceptance_nonce"],
        "started_at": started_at,
        "completed_at": iso_now(),
        "pid": os.getpid(),
        "iterations": iterations,
        "result_sha256": digest.hexdigest(),
        "message": "fixed safe fake task completed; no user command was executed",
    }
    temporary = output.with_suffix(output.suffix + ".tmp")
    temporary.write_text(json.dumps(payload, ensure_ascii=False, indent=2), encoding="utf-8")
    os.replace(temporary, output)
    return output


def main(argv=None) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--job", required=True)
    args = parser.parse_args(argv)
    result = run_job(Path(args.job))
    print(json.dumps({"result": str(result)}, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
